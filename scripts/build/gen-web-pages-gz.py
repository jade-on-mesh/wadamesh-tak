#!/usr/bin/env python3
"""Gzip the built-in web pages (Wadamesh-tak).

The web terminal, mirror/info and file transfer pages are plain C string
literals: about 63 KB of HTML and script in the app image. Browsers all take
gzip, so this writes src/helpers/esp32/web_pages_gz.h with each page's body
gzipped (and Content-Encoding / Content-Length added to its headers), about a
quarter of the size. WebSocketCompanionServer.cpp serves those when the header
exists; the original literals are then unreferenced and the linker drops them.

The pages stay where upstream keeps them, so an upstream change to a page is
picked up by the next build. Run by pre_gen_baked.py; each result is checked by
unzipping it again before it is written.
"""
import gzip, os, re, sys

try:
    ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
except NameError:
    ROOT = os.getcwd()
ESP = os.path.join(ROOT, "src", "helpers", "esp32")
OUT = os.path.join(ESP, "web_pages_gz.h")
PAGES = [
    ("WebSocketCompanionServer.cpp", "WS_HTTP_INFO_PAGE"),
    ("WebSocketCompanionServer.cpp", "WS_HTML_TERMINAL_PAGE"),
    ("WebFileTransferPage.h", "WS_HTTP_FILES_PAGE"),
]

_ESC = {"n": b"\n", "r": b"\r", "t": b"\t", '"': b'"', "'": b"'", "\\": b"\\", "?": b"?", "0": b"\0", "a": b"\a",
        "b": b"\b", "f": b"\f", "v": b"\v"}


def unescape(body):
    """The bytes of one C string literal's contents."""
    out = bytearray()
    raw = body.encode("utf-8")
    i = 0
    while i < len(raw):
        c = raw[i:i + 1]
        if c != b"\\":
            out += c
            i += 1
            continue
        n = raw[i + 1:i + 2].decode()
        if n == "x":
            m = re.match(rb"[0-9a-fA-F]+", raw[i + 2:])
            out.append(int(m.group(0), 16) & 0xFF)
            i += 2 + len(m.group(0))
        elif n in "01234567":
            m = re.match(rb"[0-7]{1,3}", raw[i + 1:])
            out.append(int(m.group(0), 8) & 0xFF)
            i += 1 + len(m.group(0))
        elif n in _ESC:
            out += _ESC[n]
            i += 2
        else:
            raise ValueError("unknown escape \\" + n)
    return bytes(out)


def literal(src, name):
    """The bytes of `static const char NAME[] = "..." "...";`."""
    m = re.search(r"static\s+const\s+char\s+" + name + r"\s*\[\s*\]\s*=", src)
    if not m:
        raise ValueError(name + " not found")
    i = m.end()
    out = bytearray()
    while True:
        while src[i] in " \t\r\n":
            i += 1
        if src.startswith("//", i):
            i = src.index("\n", i)
            continue
        if src.startswith("/*", i):
            i = src.index("*/", i) + 2
            continue
        if src[i] == ";":
            return bytes(out)
        if src.startswith('R"', i):   # raw string: R"delim( ... )delim"
            k = src.index("(", i)
            end = ")" + src[i + 2:k] + '"'
            j = src.index(end, k)
            out += src[k + 1:j].encode("utf-8")
            i = j + len(end)
            continue
        ident = re.match(r"[A-Za-z_]\w*", src[i:])
        if ident:
            # A macro of string literals in the page (upstream's WS_AUTH_HTML /
            # WS_AUTH_JS): its literals, spliced in.
            out += macro(src, ident.group(0), name)
            i += len(ident.group(0))
            continue
        if src[i] != '"':
            raise ValueError(name + ": not a plain string literal at " + src[i:i + 20])
        j = i + 1
        while src[j] != '"':
            j += 2 if src[j] == "\\" else 1
        out += unescape(src[i + 1:j])
        i = j + 1


def macro(src, ident, name):
    """The bytes of `#define IDENT "..." "..."` (continued with backslashes)."""
    m = re.search(r"^#define\s+" + ident + r"\b[ \t]*((?:.*\\\n)*.*)$", src, re.M)
    if not m:
        raise ValueError(name + ": " + ident + " is not a #define in the same file")
    body = re.sub(r"\\\n", "\n", m.group(1))
    return literal("static const char X[] = " + body + ";", "X")


def page_gz(raw):
    head, sep, body = raw.partition(b"\r\n\r\n")
    if not sep or not head.startswith(b"HTTP/1.1"):
        raise ValueError("no HTTP header")
    z = gzip.compress(body, compresslevel=9, mtime=0)
    if gzip.decompress(z) != body:
        raise ValueError("gzip round trip failed")
    head += b"\r\nContent-Encoding: gzip\r\nContent-Length: %d" % len(z)
    return head + b"\r\n\r\n" + z


def main():
    srcs = sorted({os.path.join(ESP, f) for f, _ in PAGES} | {os.path.abspath(__file__)})
    if os.path.exists(OUT) and os.path.getmtime(OUT) >= max(os.path.getmtime(s) for s in srcs):
        return
    parts = ["// Generated by scripts/build/gen-web-pages-gz.py; do not edit.\n#pragma once\n#include <stdint.h>\n"]
    total_in = total_out = 0
    for fname, name in PAGES:
        src = open(os.path.join(ESP, fname), encoding="utf-8").read()
        raw = literal(src, name)
        gz = page_gz(raw)
        total_in += len(raw)
        total_out += len(gz)
        rows = ",".join(str(b) for b in gz)
        rows = re.sub(r"((?:\d+,){40})", r"\1\n  ", rows)
        parts.append("static const uint8_t %s_GZ[%d] = {\n  %s};\n" % (name, len(gz), rows))
    tmp = OUT + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(parts))
    os.replace(tmp, OUT)
    print("web pages: gzipped %d -> %d bytes (web_pages_gz.h)" % (total_in, total_out))


if __name__ == "__main__":
    main()
